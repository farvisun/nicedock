import AppKit
import ImageIO
import Observation
import SwiftUI

struct UtilClipItem: Identifiable {
    let id = UUID()
    var text: String?
    /// PNG of a downsampled copy (max 640 px) — what gets copied back.
    var imageData: Data?
    /// Tiny preview for the list.
    var thumb: NSImage?
    var size: CGSize = .zero
    var date = Date()
    var pinned = false
    let signature: Int
}

/// Clipboard history. Only `changeCount` is checked (every 0.75 s) and only while a clipboard tile exists;
/// contents are read once per change. Password managers' concealed/transient items are skipped.
@Observable
@MainActor
final class UtilClipboardService: DemandDriven {
    static let shared = UtilClipboardService()

    private(set) var items: [UtilClipItem] = []
    /// False when macOS pasteboard privacy would prompt on every read and the user hasn't opted in.
    private(set) var captureAllowed = true

    @ObservationIgnored private var subscribers = Set<String>()
    @ObservationIgnored private var timer: Timer?
    @ObservationIgnored private var lastChange = NSPasteboard.general.changeCount

    private static let maxText = 30
    private static let maxImages = 6
    private static let pinnedKey = "UtilClipboard.pinned"
    private static let optInKey = "UtilClipboard.optIn"
    private static let skipTypes: Set<String> = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
                                                 "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword"]

    private init() {
        let pinned = UserDefaults.standard.stringArray(forKey: Self.pinnedKey) ?? []
        items = pinned.map { UtilClipItem(text: $0, pinned: true, signature: $0.hashValue) }
    }

    var count: Int { items.count }

    func subscribe(_ id: String) {
        subscribers.insert(id)
        guard subscribers.count == 1, !UtilEnv.rendering else { return }
        updateCaptureAllowed()
        lastChange = NSPasteboard.general.changeCount
        let t = Timer(timeInterval: 0.75, repeats: true) { _ in MainActor.assumeIsolated { UtilClipboardService.shared.tick() } }
        t.tolerance = 0.25
        RunLoop.main.add(t, forMode: .common)
        timer = t
    }

    func unsubscribe(_ id: String) {
        subscribers.remove(id)
        if subscribers.isEmpty { timer?.invalidate(); timer = nil }
    }

    func updateCaptureAllowed() {
        if #available(macOS 15.4, *) {
            switch NSPasteboard.general.accessBehavior {
            case .alwaysAllow: captureAllowed = true
            case .alwaysDeny: captureAllowed = false
            default:
                // Programmatic reads only raise the privacy alert from macOS 26 on.
                captureAllowed = ProcessInfo.processInfo.operatingSystemVersion.majorVersion < 26
                    || UserDefaults.standard.bool(forKey: Self.optInKey)
            }
        } else {
            captureAllowed = true
        }
    }

    /// User-initiated opt-in (may show the system "paste from other apps" alert once).
    func enableCapture() {
        UserDefaults.standard.set(true, forKey: Self.optInKey)
        updateCaptureAllowed()
        lastChange = -1
        tick()
    }

    private func tick() {
        let pb = NSPasteboard.general
        let change = pb.changeCount
        guard change != lastChange else { return }
        lastChange = change
        guard captureAllowed else { return }
        let types = Set((pb.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: Self.skipTypes) else { return }

        if let s = pb.string(forType: .string), !s.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            addText(String(s.prefix(20_000)))
        } else if let data = pb.data(forType: .png) ?? pb.data(forType: .tiff) {
            Task {
                guard let processed = await Self.process(data) else { return }
                self.addImage(processed)
            }
        }
    }

    private func addText(_ s: String) {
        let sig = s.hashValue
        if let i = items.firstIndex(where: { $0.signature == sig }) {
            var item = items.remove(at: i)
            item.date = Date()
            insert(item)
        } else {
            insert(UtilClipItem(text: s, signature: sig))
        }
    }

    private func addImage(_ p: (png: Data, thumb: NSImage, size: CGSize)) {
        let sig = p.png.hashValue
        if let i = items.firstIndex(where: { $0.signature == sig }) {
            var item = items.remove(at: i)
            item.date = Date()
            insert(item)
            return
        }
        insert(UtilClipItem(imageData: p.png, thumb: p.thumb, size: p.size, signature: sig))
    }

    private func insert(_ item: UtilClipItem) {
        var list = items
        let firstUnpinned = list.firstIndex { !$0.pinned } ?? list.count
        list.insert(item, at: item.pinned ? 0 : firstUnpinned)
        // Trim unpinned overflow per kind.
        var texts = 0, images = 0
        list.removeAll { it in
            guard !it.pinned else { return false }
            if it.imageData != nil { images += 1; return images > Self.maxImages }
            texts += 1
            return texts > Self.maxText
        }
        items = list
    }

    nonisolated private static func process(_ data: Data) async -> (png: Data, thumb: NSImage, size: CGSize)? {
        await Task.detached(priority: .utility) { () -> (png: Data, thumb: NSImage, size: CGSize)? in
            guard let src = CGImageSourceCreateWithData(data as CFData, nil) else { return nil }
            func thumb(_ px: Int) -> CGImage? {
                let opts: [CFString: Any] = [kCGImageSourceCreateThumbnailFromImageAlways: true, kCGImageSourceThumbnailMaxPixelSize: px,
                                             kCGImageSourceCreateThumbnailWithTransform: true]
                return CGImageSourceCreateThumbnailAtIndex(src, 0, opts as CFDictionary)
            }
            guard let big = thumb(640), let small = thumb(96) else { return nil }
            let rep = NSBitmapImageRep(cgImage: big)
            guard let png = rep.representation(using: .png, properties: [:]) else { return nil }
            let props = CGImageSourceCopyPropertiesAtIndex(src, 0, nil) as? [CFString: Any]
            let w = props?[kCGImagePropertyPixelWidth] as? Int ?? big.width
            let h = props?[kCGImagePropertyPixelHeight] as? Int ?? big.height
            return (png, NSImage(cgImage: small, size: NSSize(width: small.width / 2, height: small.height / 2)), CGSize(width: w, height: h))
        }.value
    }

    // MARK: Actions

    func copy(_ item: UtilClipItem) {
        let pb = NSPasteboard.general
        pb.clearContents()
        if let text = item.text {
            pb.setString(text, forType: .string)
        } else if let data = item.imageData, let image = NSImage(data: data) {
            pb.writeObjects([image])
        }
        lastChange = pb.changeCount
        if let i = items.firstIndex(where: { $0.id == item.id }), !items[i].pinned {
            var moved = items.remove(at: i)
            moved.date = Date()
            insert(moved)
        }
    }

    func togglePin(_ item: UtilClipItem) {
        guard let i = items.firstIndex(where: { $0.id == item.id }) else { return }
        var it = items.remove(at: i)
        it.pinned.toggle()
        insert(it)
        savePinned()
    }

    func remove(_ item: UtilClipItem) {
        items.removeAll { $0.id == item.id }
        savePinned()
    }

    func clear() {
        items.removeAll { !$0.pinned }
    }

    private func savePinned() {
        UserDefaults.standard.set(items.filter(\.pinned).compactMap(\.text), forKey: Self.pinnedKey)
    }
}

// MARK: - Views

struct UtilClipboardTile: View {
    let w: WidgetInstance
    @Environment(\.metrics) private var m
    @Environment(\.palette) private var p
    private var service: UtilClipboardService { .shared }

    var body: some View {
        let n = service.count
        Tile(width: w.kind.spec.width) {
            VStack(spacing: m.u(3)) {
                Image(systemName: "doc.on.clipboard")
                    .font(.system(size: m.u(n > 0 ? 19 : 22), weight: .medium))
                    .foregroundStyle(p.secondary)
                if n > 0 {
                    Text(verbatim: Fmt.int(n)).dock(11, .bold, mono: true)
                }
            }
        }
        .onTapGesture { UtilClipboardPanel.toggle(w) }
        .demand(UtilClipboardService.shared)
    }
}

@MainActor
enum UtilClipboardPanel {
    static func toggle(_ w: WidgetInstance) {
        Panels.shared.toggle(w.id) { UtilClipboardPanelView() }
    }
}

private struct UtilClipboardPanelView: View {
    @Environment(\.palette) private var p
    private var service: UtilClipboardService { .shared }

    var body: some View {
        VStack(alignment: .leading, spacing: 10) {
            PanelHeader(title: L("Clipboard"), subtitle: L("%@ items", Fmt.int(service.count))) {
                if service.items.contains(where: { !$0.pinned }) {
                    Button(L("Clear")) { service.clear() }
                        .buttonStyle(.plain)
                        .font(.dock(12, .semibold))
                        .foregroundStyle(p.accent(.cdRed))
                }
            }
            if !service.captureAllowed {
                VStack(alignment: .leading, spacing: 8) {
                    Text(L("macOS asks before apps read the clipboard. Allow CoolDock to keep a history, or set it to Always Allow in Privacy & Security."))
                        .font(.dock(11, .medium)).foregroundStyle(p.secondary)
                        .fixedSize(horizontal: false, vertical: true)
                    HStack {
                        Button(L("Enable History")) { service.enableCapture() }
                        Button(L("Privacy Settings…")) { Open.url("x-apple.systempreferences:com.apple.preference.security?Privacy_Pasteboard") }
                    }
                    .controlSize(.small)
                }
                .padding(10)
                .background(RoundedRectangle(cornerRadius: 10, style: .continuous).fill(p.control))
            }
            if service.items.isEmpty {
                Text(L("Copied text and images appear here."))
                    .font(.dock(12, .medium)).foregroundStyle(p.tertiary)
                    .frame(maxWidth: .infinity, minHeight: 60)
            } else {
                ScrollView {
                    LazyVStack(spacing: 4) {
                        ForEach(service.items) { UtilClipRow(item: $0) }
                    }
                }
                .frame(height: min(CGFloat(service.items.count) * 50, 380))
            }
        }
        .frame(width: 320)
        .onAppear { service.updateCaptureAllowed() }
    }
}

private struct UtilClipRow: View {
    @Environment(\.palette) private var p
    var item: UtilClipItem
    @State private var hover = false

    var body: some View {
        HStack(spacing: 10) {
            Group {
                if let thumb = item.thumb {
                    Image(nsImage: thumb).resizable().aspectRatio(contentMode: .fill)
                } else {
                    Image(systemName: "text.alignleft").font(.system(size: 12, weight: .semibold)).foregroundStyle(p.secondary)
                }
            }
            .frame(width: 36, height: 36)
            .background(RoundedRectangle(cornerRadius: 7, style: .continuous).fill(p.control))
            .clipShape(RoundedRectangle(cornerRadius: 7, style: .continuous))
            VStack(alignment: .leading, spacing: 2) {
                if let text = item.text {
                    Text(verbatim: text.trimmingCharacters(in: .whitespacesAndNewlines))
                        .font(.dock(12, .medium)).foregroundStyle(p.primary).lineLimit(2)
                } else {
                    Text(L("Image")).font(.dock(12, .semibold)).foregroundStyle(p.primary)
                }
                Text(verbatim: subtitle).font(.dock(10, .medium)).foregroundStyle(p.tertiary).lineLimit(1)
            }
            Spacer(minLength: 4)
            Button { UtilClipboardService.shared.togglePin(item) } label: {
                Image(systemName: item.pinned ? "pin.fill" : "pin")
                    .font(.system(size: 11, weight: .semibold))
                    .foregroundStyle(item.pinned ? p.accent(.cdOrange) : p.tertiary)
                    .frame(width: 22, height: 22)
                    .contentShape(Rectangle())
            }
            .buttonStyle(.plain)
            .opacity(item.pinned || hover ? 1 : 0.0001)
            .help(item.pinned ? L("Unpin") : L("Pin"))
        }
        .padding(.horizontal, 6)
        .padding(.vertical, 4)
        .background(RoundedRectangle(cornerRadius: 8, style: .continuous).fill(hover ? p.control : .clear))
        .contentShape(Rectangle())
        .onHover { hover = $0 }
        .onTapGesture {
            UtilClipboardService.shared.copy(item)
            Panels.shared.close()
        }
        .contextMenu {
            Button(L("Copy")) { UtilClipboardService.shared.copy(item) }
            Button(item.pinned ? L("Unpin") : L("Pin")) { UtilClipboardService.shared.togglePin(item) }
            Button(L("Delete"), role: .destructive) { UtilClipboardService.shared.remove(item) }
        }
    }

    private var subtitle: String {
        let when = UtilRelative.string(item.date)
        if item.imageData != nil, item.size != .zero {
            return Fmt.digits("\(Int(item.size.width))×\(Int(item.size.height))") + " · " + when
        }
        if let t = item.text { return L("%@ characters", Fmt.int(t.count)) + " · " + when }
        return when
    }
}

enum UtilRelative {
    nonisolated(unsafe) private static var formatter: RelativeDateTimeFormatter?
    nonisolated(unsafe) private static var locale: Locale?

    static func string(_ date: Date) -> String {
        if Date().timeIntervalSince(date) < 60 { return L("Just now") }
        if formatter == nil || locale != Fmt.locale {
            let f = RelativeDateTimeFormatter()
            f.unitsStyle = .short
            f.locale = Fmt.locale
            formatter = f
            locale = Fmt.locale
        }
        return formatter!.localizedString(for: date, relativeTo: Date())
    }
}
