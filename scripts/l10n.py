#!/usr/bin/env python3
"""Localization helper.

    scripts/l10n.py extract          # regenerate Resources/en.lproj/Localizable.strings from the sources
    scripts/l10n.py check            # list missing / stale keys per language
    scripts/l10n.py missing fa       # print missing keys for one language as a .strings template
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "Sources" / "CoolDock"
RES = ROOT / "Resources"

STR = r'"((?:[^"\\]|\\.)*)"'
PATTERNS = [
    re.compile(r'\bL\(\s*' + STR),
    # Catalog / schema literals that are localized at the point of use.
    re.compile(r'\btitle:\s*' + STR),
    re.compile(r'\bsummary:\s*' + STR),
    re.compile(r'\bhelp:\s*' + STR),
    re.compile(r'\bunit:\s*' + STR),
]
LD_PATTERN = re.compile(r'\bLD\(\s*' + STR + r'\s*,\s*' + STR)
EXTRA = ["KB", "MB", "GB", "TB", "/s", "N", "NE", "E", "SE", "S", "SW", "W", "NW", "km/h", "mph"]


DEFAULTS = {}


def extract_keys():
    keys = []
    seen = set()
    for path in sorted(SRC.rglob("*.swift")):
        text = path.read_text(encoding="utf-8")
        for pat in PATTERNS:
            for m in pat.finditer(text):
                k = m.group(1)
                if not k or k in seen or "\\(" in k:
                    continue
                seen.add(k)
                keys.append(k)
    for path in sorted(SRC.rglob("*.swift")):
        for m in LD_PATTERN.finditer(path.read_text(encoding="utf-8")):
            if m.group(1) not in seen:
                seen.add(m.group(1))
                keys.append(m.group(1))
                DEFAULTS[m.group(1)] = m.group(2)
    for k in EXTRA:
        if k not in seen:
            seen.add(k)
            keys.append(k)
    return keys


def parse_strings(path):
    out = {}
    if not path.exists():
        return out
    text = path.read_text(encoding="utf-8")
    for m in re.finditer(r'^\s*' + STR + r'\s*=\s*' + STR + r'\s*;', text, re.M):
        out[m.group(1)] = m.group(2)
    return out


def write_en(keys):
    lines = ["/* NiceDock — English source strings. Keys are the English text. Generated by scripts/l10n.py extract. */", ""]
    for k in keys:
        lines.append(f'"{k}" = "{DEFAULTS.get(k, k)}";')
    (RES / "en.lproj").mkdir(parents=True, exist_ok=True)
    (RES / "en.lproj" / "Localizable.strings").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{len(keys)} keys")


def main():
    cmd = sys.argv[1] if len(sys.argv) > 1 else "check"
    keys = extract_keys()
    if cmd == "extract":
        write_en(keys)
    elif cmd == "check":
        for d in sorted(RES.glob("*.lproj")):
            if d.name == "en.lproj":
                continue
            table = parse_strings(d / "Localizable.strings")
            missing = [k for k in keys if k not in table]
            stale = [k for k in table if k not in set(keys)]
            print(f"{d.stem:8} {len(table):5} translated  {len(missing):4} missing  {len(stale):4} stale")
    elif cmd == "missing":
        lang = sys.argv[2]
        table = parse_strings(RES / f"{lang}.lproj" / "Localizable.strings")
        for k in keys:
            if k not in table:
                print(f'"{k}" = "";')


if __name__ == "__main__":
    main()
